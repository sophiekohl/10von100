begin;
create function pg_temp.ok(v boolean,label text) returns void language plpgsql as $$begin if v is distinct from true then raise exception 'PUSH FAIL: %',label;end if;end$$;
create temporary table push_test as select gen_random_uuid() uid,gen_random_uuid() sid,gen_random_uuid() outsider;
grant select on push_test to authenticated;
insert into auth.users(id,email)select uid,'partner-push-test@10von100.invalid' from push_test union all select outsider,'outsider@example.invalid' from push_test;
insert into auth.sessions(id,user_id)select sid,uid from push_test;
insert into public.couple_members select uid,now() from push_test;
select public.partner_pin_configure(uid,'4826',false) from push_test;
select public.partner_pin_register(uid,(select revision from private.partner_access),sid) from push_test;
select set_config('request.jwt.claims',jsonb_build_object('sub',uid,'session_id',sid,'role','authenticated')::text,true) from push_test;
select pg_temp.ok(not has_function_privilege('authenticated','public.push_worker(text,jsonb)','execute'),'member cannot read worker secrets');
select pg_temp.ok(not has_function_privilege('anon','public.push_manage(text,jsonb,text)','execute'),'anon denied');
select pg_temp.ok(not has_table_privilege('authenticated','private.push_subscriptions','select'),'subscriptions private');
set local role authenticated;
select public.push_manage('subscribe',jsonb_build_object('endpoint','https://web.push.apple.com/test-device','keys',jsonb_build_object('p256dh',repeat('a',87),'auth',repeat('b',22))));
select public.push_manage('subscribe',jsonb_build_object('endpoint','https://web.push.apple.com/test-device','keys',jsonb_build_object('p256dh',repeat('a',87),'auth',repeat('b',22))));
reset role;
select pg_temp.ok((select count(*)=1 from private.push_subscriptions),'subscribe idempotent');
-- Make subscription older, never modify real application data: local test DB only.
update private.push_subscriptions set subscribed_at=now()-interval '1 hour';
insert into public.content_items(title,unlock_at,published,push_enabled)values('DRAFT',now()-interval '1 minute',false,true),('FUTURE',now()+interval '1 hour',true,true),('SILENT',now()-interval '1 minute',true,false),('OLD',now()-interval '2 hours',true,true),('READY',now()-interval '1 minute',true,true);
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=1,'only ready item eligible');
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=0,'active lease excludes duplicate workers');
select public.push_worker('finish',jsonb_build_object('subscriptionId',subscription_id,'itemId',content_id,'lease',lease,'result','retry'))from private.push_deliveries;
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=0,'retry backoff');
update private.push_deliveries set next_attempt=now()-interval '1 second';
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=1,'retry lease');
select public.push_worker('finish',jsonb_build_object('subscriptionId',subscription_id,'itemId',content_id,'lease',lease,'result','sent'))from private.push_deliveries;
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=0,'sent not repeated');
-- Simulate a newly released second item, then PIN rotation.
insert into public.content_items(title,unlock_at,published,push_enabled) values('READY2',now()-interval '1 minute',true,true);
select public.partner_pin_revoke();
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=0,'revoked partner never notified');
set local role authenticated;
do $$begin perform public.push_manage('config');raise exception 'revoked authorization wrongly accepted';exception when insufficient_privilege then null;end$$;
reset role;
select public.partner_pin_configure(uid,'4826',false) from push_test;
select pg_temp.ok(jsonb_array_length(public.push_worker('claim'))=0,'old PIN revision never notified');
delete from auth.sessions where id=(select sid from push_test);
select pg_temp.ok((select count(*)=0 from private.push_subscriptions),'session deletion cascades subscription');
rollback;
